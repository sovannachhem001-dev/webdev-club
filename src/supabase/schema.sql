-- Allow everyone to view gallery photos
CREATE POLICY "Anyone can view gallery photos"
ON storage.objects
FOR SELECT
TO anon, authenticated
USING (
  bucket_id = 'gallery'
);

-- Allow admins to upload gallery photos
CREATE POLICY "Admins can upload gallery photos"
ON storage.objects
FOR INSERT
TO authenticated
WITH CHECK (
  bucket_id = 'gallery'
  AND EXISTS (
    SELECT 1
    FROM public.admin_users
    WHERE admin_users.user_id = auth.uid()
  )
);

-- Allow admins to delete gallery photos
CREATE POLICY "Admins can delete gallery photos"
ON storage.objects
